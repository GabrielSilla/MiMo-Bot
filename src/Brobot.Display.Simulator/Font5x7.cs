    public static byte[]? GetGlyph(char c)
    {
        int index = Chars.IndexOf(c);
        if (index >= 0)
        {
            return Glyphs[index];
        }

        // Uppercase accented letters (and anything else this tiny font has no
        // dedicated glyph for) fall back to the plain base letter rather than
        // leaving a blank gap — e.g. "NÃO" renders as "NAO". Not accurate,
        // but readable, which a dropped glyph is not.
        char stripped = StripDiacritic(c);
        return stripped != c ? GetGlyph(stripped) : null;
    }

    private static char StripDiacritic(char c) => c switch
    {
        'Á' or 'À' or 'Â' or 'Ã' => 'A',
        'É' or 'Ê' => 'E',
        'Í' => 'I',
        'Ó' or 'Ô' or 'Õ' => 'O',
        'Ú' => 'U',
        'Ç' => 'C',
        _ => c,
    };
